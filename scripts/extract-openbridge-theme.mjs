/**
 * Extracts the OpenBridge design tokens (palettes, sizes, typography) from
 * `@oicl/openbridge-webcomponents/dist/openbridge.css` and rescopes them from
 * `:root` to `.obc-helio-scope` so the tokens only apply inside our elements
 * and never leak into the surrounding HELIO application.
 *
 * To keep the extension bundle small, only tokens that the OpenBridge
 * components actually reference (directly, via a dynamically built name, or
 * transitively through another token) are kept. Component classes (radio
 * buttons etc.) and icon data URLs are dropped.
 *
 * Output: `src/openbridge/openbridgeTheme.generated.ts`
 *
 * Run with `npm run generate:theme` whenever the OpenBridge package is updated.
 */
import { readFileSync, readdirSync, writeFileSync, mkdirSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import postcss from 'postcss';

const require = createRequire(import.meta.url);
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const cssPath = require.resolve('@oicl/openbridge-webcomponents/dist/openbridge.css', {
  paths: [root],
});
const distDir = dirname(cssPath);
const outPath = resolve(root, 'src/openbridge/openbridgeTheme.generated.ts');

const SCOPE = '.obc-helio-scope';
const THEME_RE = /^:root\[data-obc-theme="(bright|day|dusk|night)"\]$/;

function rescopeSelector(selector) {
  // Default palette (`:root`) and default size (`.obc-component-size-regular`).
  if (selector === ':root' || selector === '.obc-component-size-regular' || selector === '*') {
    return SCOPE;
  }

  const theme = selector.match(THEME_RE);
  if (theme) {
    return `${SCOPE}[data-obc-theme="${theme[1]}"]`;
  }

  return null;
}

// Token prefixes that the components build at runtime, e.g. `--instrument-${x}`.
const DYNAMIC_PREFIXES = ['--instrument-', '--flash-'];
const VAR_NAME_RE = /--[a-zA-Z0-9_-]+/g;

function collectReferencedTokens(dir, found = new Set()) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const path = resolve(dir, entry.name);
    if (entry.isDirectory()) {
      collectReferencedTokens(path, found);
    } else if (entry.name.endsWith('.js')) {
      for (const name of readFileSync(path, 'utf8').match(VAR_NAME_RE) ?? []) found.add(name);
    }
  }
  return found;
}

const ast = postcss.parse(readFileSync(cssPath, 'utf8'));
const out = postcss.root();

for (const node of ast.nodes) {
  if (node.type === 'atrule' && node.name === 'property') {
    out.append(node.clone());
    continue;
  }

  if (node.type !== 'rule') continue;

  const selectors = [...new Set(node.selectors.map(rescopeSelector))];
  if (selectors.includes(null)) continue;

  const rule = node.clone({ selectors });
  rule.walkDecls((decl) => {
    // Only keep custom properties, and skip the (large) icon data URLs.
    if (!decl.prop.startsWith('--') || decl.prop.startsWith('--icon-')) {
      decl.remove();
    }
  });

  if (rule.nodes.length > 0) out.append(rule);
}

// Keep tokens used by components, then add everything they depend on.
const used = collectReferencedTokens(distDir);
const dependencies = new Map();
out.walkDecls((decl) => {
  const deps = dependencies.get(decl.prop) ?? new Set();
  for (const name of decl.value.match(VAR_NAME_RE) ?? []) deps.add(name);
  dependencies.set(decl.prop, deps);
});

const keep = new Set();
const queue = [...dependencies.keys()].filter(
  (name) => used.has(name) || DYNAMIC_PREFIXES.some((prefix) => name.startsWith(prefix)),
);
while (queue.length > 0) {
  const name = queue.pop();
  if (keep.has(name)) continue;
  keep.add(name);
  queue.push(...(dependencies.get(name) ?? []));
}

out.walkDecls((decl) => {
  if (!keep.has(decl.prop)) decl.remove();
});
out.walkRules((rule) => {
  if (rule.nodes.length === 0) rule.remove();
});

const css = out
  .toString()
  .replace(/\n\s*\n/g, '\n')
  .replace(/\s*\n\s*/g, '');

mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(
  outPath,
  `// AUTO-GENERATED by scripts/extract-openbridge-theme.mjs – do not edit.\n` +
    `export const OPENBRIDGE_SCOPE_CLASS = '${SCOPE.slice(1)}';\n` +
    `export const openbridgeThemeCss = ${JSON.stringify(css)};\n`,
);

console.log(`Wrote ${outPath} (${(css.length / 1024).toFixed(1)} KiB of CSS)`);

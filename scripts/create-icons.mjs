/**
 * Adds the OpenBridge icons (`<obi-*>` in `@oicl/openbridge-webcomponents`)
 * to the HELIO extension as `createIcon` icons:
 *
 *   <src>/icons/openbridgeIcons.generated.ts   icon data (SVG markup, names, categories)
 *   <src>/icons/openbridgeIcons.tsx            turns the data into HELIO icons (created if missing)
 *   <src>/main.tsx                             registration (`icons: openBridgeIcons`)
 *
 * The SVGs are taken from the icons' `currentColor` variant, so they take the
 * color HELIO renders them with. Categories follow OpenBridge's own grouping
 * (`dist/icons/names.js`), e.g. "OpenBridge: Maritime icons / Chart targets".
 *
 * Icon names are derived from the OpenBridge id only (`ais-proposal` →
 * "AIS Proposal"), so filtering with --groups never renames an icon. HELIO
 * uses the name as ID: icons that disappear (filtered out, or removed in an
 * OpenBridge update) break the projects that use them.
 *
 * Usage:
 *   node scripts/create-icons.mjs [options]
 *   node scripts/create-icons.mjs --list
 *
 *   --groups a,b           only these groups or "group / subgroup"s (case-insensitive),
 *                          e.g. --groups "Maritime icons,UI icons / General"
 *   --list                 print the OpenBridge groups with icon counts
 *   --root <dir>           project root (default: nearest package.json from cwd)
 *   --src <dir>            source folder relative to the root (default: src)
 *   --main <file>          extension entry relative to the root (default: <src>/main.tsx)
 *   --no-register          do not touch main.tsx
 *   --dry-run              print what would be generated, write nothing
 *   --print-runtime <file> print an embedded runtime file, e.g. icons/openbridgeIcons.tsx
 *   --sync-runtime         update the embedded runtime file from <src> (maintainers)
 */
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, relative, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const SCRIPT_PATH = fileURLToPath(import.meta.url);
const GENERATED_MARKER = 'Generated by `create-icons.mjs`';
const DATA_FILE = 'icons/openbridgeIcons.generated.ts';
const RUNTIME_FILE = 'icons/openbridgeIcons.tsx';
const EXPORT_NAME = 'openBridgeIcons';


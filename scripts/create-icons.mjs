function openBridgeIcons() {
  const pkgDir = inRoot('node_modules/@oicl/openbridge-webcomponents');
  if (!existsSync(pkgDir)) {
    fail('Package @oicl/openbridge-webcomponents is not installed. Run: npm install');
  }
  const iconsDir = resolve(pkgDir, 'dist/icons');
  const { version } = JSON.parse(readFileSync(resolve(pkgDir, 'package.json'), 'utf8'));
  return import(pathToFileURL(resolve(iconsDir, 'names.js')).href).then(({ iconIds }) => {
    /** `iconIds`: `{ [id]: [group, subgroup] }`, e.g. `"ais-proposal": ["Maritime icons", "Chart targets"]`. */
    const catalog = Object.entries(iconIds).map(([id, [group, subgroup]]) => ({
      id,
      group: group.trim(),
      subgroup: subgroup.trim(),
    }));

    if (args.list) {
      const counts = new Map();
      for (const { group, subgroup } of catalog) {
        const subgroups = counts.get(group) ?? new Map();
        subgroups.set(subgroup, (subgroups.get(subgroup) ?? 0) + 1);
        counts.set(group, subgroups);
      }
      for (const [group, subgroups] of [...counts].sort(([a], [b]) => a.localeCompare(b))) {
        const total = [...subgroups.values()].reduce((sum, n) => sum + n, 0);
        console.log(`${group} (${total})`);
        for (const [subgroup, n] of [...subgroups].sort(([a], [b]) => a.localeCompare(b))) {
          console.log(`  ${group} / ${subgroup} (${n})`);
        }
      }
      console.log(`\n${catalog.length} icons in @oicl/openbridge-webcomponents ${version}.`);
      process.exit(0);
    }

    const normalize = (value) =>
      value
        .toLowerCase()
        .replace(/\s*\/\s*/g, ' / ')
        .trim();
    const filters = args.groups?.split(',').map(normalize).filter(Boolean);
    if (filters) {
      const known = catalog.flatMap(({ group, subgroup }) => [group, `${group} / ${subgroup}`]);
      const unknown = filters.filter((f) => !known.some((k) => normalize(k) === f));
      if (unknown.length) fail(`Unknown group(s): ${unknown.join(', ')}. See --list.`);
    }
    const selected = filters
      ? catalog.filter(({ group, subgroup }) =>
          filters.some((f) => f === normalize(group) || f === normalize(`${group} / ${subgroup}`)),
        )
      : catalog;

    return {
      source: `@oicl/openbridge-webcomponents ${version}`,
      icons: selected.map((icon) => ({
        name: icon.id
          .split('-')
          .map((word) => SPELLINGS[word] ?? word.charAt(0).toUpperCase() + word.slice(1))
          .join(' '),
        description: `obi-${icon.id}`,
        category:
          icon.group === icon.subgroup
            ? `OpenBridge: ${icon.group}`
            : `OpenBridge: ${icon.group} / ${icon.subgroup}`,
        ...extractOpenBridgeSvg(iconsDir, icon.id),
      })),
    };
  });
}

/**
 * Reads the `currentColor` SVG (`this.icon = svg\`…\``) of an OpenBridge icon
 * module and returns its size and minified inner markup.
 */
function extractOpenBridgeSvg(iconsDir, id) {
  const file = resolve(iconsDir, `icon-${id}.js`);
  const source = readIfExists(file);
  if (source === undefined) fail(`Missing icon module: ${relative(root, file)}`);
  const template = source.match(/this\.icon = svg`([\s\S]*?)`;/)?.[1];
  if (template === undefined || template.includes('${')) {
    fail(`Unexpected source in ${relative(root, file)} – the extraction needs updating.`);
  }
  const svg = template.match(/^\s*<svg\b([^>]*)>([\s\S]*)<\/svg>\s*$/);
  const viewBox = svg?.[1].match(/\bviewBox="0 0 ([\d.]+) ([\d.]+)"/);
  if (!svg || !viewBox || !/\bfill="currentColor"/.test(svg[1])) {
    fail(`Unexpected <svg> root in ${relative(root, file)} – the extraction needs updating.`);
  }
  return {
    width: Number(viewBox[1]),
    height: Number(viewBox[2]),
    markup: minify(prefixIds(svg[2], `obi-${id}-`)),
  };
}


// ── CLI ──────────────────────────────────────────────────────────────────

const FLAGS = ['dry-run', 'list', 'no-register', 'sync-runtime'];

function parseArgs(argv) {
  const args = { _: [] };
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    if (!arg.startsWith('--')) args._.push(arg);
    else if (FLAGS.includes(arg.slice(2))) args[arg.slice(2)] = true;
    else args[arg.slice(2)] = argv[++i];
  }
  return args;
}

const args = parseArgs(process.argv.slice(2));

function fail(message) {
  console.error(`\x1b[31m${message}\x1b[0m`);
  process.exit(1);
}

const warnings = [];
const warn = (message) => warnings.push(message);

if (args['print-runtime']) {
  const source = runtimeFiles()[args['print-runtime']];
  if (!source) fail(`Unknown runtime file. Available: ${Object.keys(runtimeFiles()).join(', ')}`);
  process.stdout.write(source);
  process.exit(0);
}

// ── Project layout ───────────────────────────────────────────────────────

function findRoot() {
  if (args.root) return resolve(args.root);
  for (let dir = process.cwd(); ; dir = dirname(dir)) {
    if (existsSync(resolve(dir, 'package.json'))) return dir;
    if (dirname(dir) === dir) return resolve(dirname(SCRIPT_PATH), '..');
  }
}

const root = findRoot();
const srcDir = args.src ?? 'src';
const mainFile = args.main ?? `${srcDir}/main.tsx`;
const inRoot = (...parts) => resolve(root, ...parts);
const inSrc = (...parts) => resolve(root, srcDir, ...parts);
const readIfExists = (path) => (existsSync(path) ? readFileSync(path, 'utf8') : undefined);

if (args['sync-runtime']) {
  const self = readFileSync(SCRIPT_PATH, 'utf8');
  // lastIndexOf: the marker strings also appear in this code.
  const start = self.lastIndexOf('// @runtime-files-start');
  const end = self.lastIndexOf('// @runtime-files-end');
  const path = inSrc(RUNTIME_FILE);
  if (!existsSync(path)) fail(`Cannot sync: ${relative(root, path)} is missing.`);
  const entry = `${JSON.stringify(RUNTIME_FILE)}: ${JSON.stringify(readFileSync(path, 'utf8'))},`;
  const block = `// @runtime-files-start\n// prettier-ignore\nfunction syncedRuntimeFiles() {\n  return {\n    ${entry}\n  };\n}\n`;
  writeFileSync(SCRIPT_PATH, self.slice(0, start) + block + self.slice(end));
  console.log(`Embedded runtime file updated from ${srcDir}/.`);
  process.exit(0);
}

const pkgDir = inRoot('node_modules/@oicl/openbridge-webcomponents');
if (!existsSync(pkgDir)) {
  fail('Package @oicl/openbridge-webcomponents is not installed. Run: npm install');
}
if (!existsSync(inRoot('node_modules/@hmiproject/helio-sdk'))) {
  fail('Package @hmiproject/helio-sdk is not installed. Run: npm install');
}
const iconsDir = resolve(pkgDir, 'dist/icons');
const { version } = JSON.parse(readFileSync(resolve(pkgDir, 'package.json'), 'utf8'));

// ── Catalog ──────────────────────────────────────────────────────────────

/** `{ [id]: [group, subgroup] }`, e.g. `"ais-proposal": ["Maritime icons", "Chart targets"]`. */
const { iconIds } = await import(pathToFileURL(resolve(iconsDir, 'names.js')).href);
const catalog = Object.entries(iconIds).map(([id, [group, subgroup]]) => ({
  id,
  group: group.trim(),
  subgroup: subgroup.trim(),
}));

if (args.list) {
  const counts = new Map();
  for (const { group, subgroup } of catalog) {
    const subgroups = counts.get(group) ?? new Map();
    subgroups.set(subgroup, (subgroups.get(subgroup) ?? 0) + 1);
    counts.set(group, subgroups);
  }
  for (const [group, subgroups] of [...counts].sort(([a], [b]) => a.localeCompare(b))) {
    const total = [...subgroups.values()].reduce((sum, n) => sum + n, 0);
    console.log(`${group} (${total})`);
    for (const [subgroup, n] of [...subgroups].sort(([a], [b]) => a.localeCompare(b))) {
      console.log(`  ${group} / ${subgroup} (${n})`);
    }
  }
  console.log(`\n${catalog.length} icons in @oicl/openbridge-webcomponents ${version}.`);
  process.exit(0);
}

const normalize = (value) =>
  value
    .toLowerCase()
    .replace(/\s*\/\s*/g, ' / ')
    .trim();
const filters = args.groups?.split(',').map(normalize).filter(Boolean);
const selected = filters
  ? catalog.filter(({ group, subgroup }) =>
      filters.some((f) => f === normalize(group) || f === normalize(`${group} / ${subgroup}`)),
    )
  : catalog;

if (filters) {
  const known = new Set(
    catalog.flatMap(({ group, subgroup }) => [group, `${group} / ${subgroup}`]),
  );
  const unknown = filters.filter((f) => ![...known].some((k) => normalize(k) === f));
  if (unknown.length) fail(`Unknown group(s): ${unknown.join(', ')}. See --list.`);
}
if (selected.length === 0) fail('No icons selected.');

const categoryOf = ({ group, subgroup }) =>
  group === subgroup ? `OpenBridge: ${group}` : `OpenBridge: ${group} / ${subgroup}`;

function iconName(id) {
  return id
    .split('-')
    .map((word) => SPELLINGS[word] ?? word.charAt(0).toUpperCase() + word.slice(1))
    .join(' ');
}

// ── SVG extraction ───────────────────────────────────────────────────────

/**
 * Reads the `currentColor` SVG (`this.icon = svg\`…\``) of an OpenBridge icon
 * module and returns its size and minified inner markup. Element ids are
 * prefixed per icon so icons on the same page cannot pick up each other's
 * clip paths, masks or filters.
 */
function extractSvg(id) {
  const file = resolve(iconsDir, `icon-${id}.js`);
  const source = readIfExists(file);
  if (source === undefined) fail(`Missing icon module: ${relative(root, file)}`);
  const template = source.match(/this\.icon = svg`([\s\S]*?)`;/)?.[1];
  if (template === undefined || template.includes('${')) {
    fail(`Unexpected source in ${relative(root, file)} – the extraction needs updating.`);
  }
  const svg = template.match(/^\s*<svg\b([^>]*)>([\s\S]*)<\/svg>\s*$/);
  const viewBox = svg?.[1].match(/\bviewBox="0 0 ([\d.]+) ([\d.]+)"/);
  if (!svg || !viewBox || !/\bfill="currentColor"/.test(svg[1])) {
    fail(`Unexpected <svg> root in ${relative(root, file)} – the extraction needs updating.`);
  }
  const prefix = `obi-${id}-`;
  const markup = svg[2]
    .replace(/\s+id="([^"]+)"/g, ` id="${prefix}$1"`)
    .replace(/url\(#([^)]+)\)/g, `url(#${prefix}$1)`)
    .replace(/href="#([^"]+)"/g, `href="#${prefix}$1"`)
    .replace(/>\s+</g, '><')
    .replace(/\s+/g, ' ')
    .trim();
  return { width: Number(viewBox[1]), height: Number(viewBox[2]), markup };
}

const categories = [...new Set(selected.map(categoryOf))].sort((a, b) => a.localeCompare(b));
const byName = new Map();
const entries = selected.map((icon) => {
  const name = iconName(icon.id);
  if (byName.has(name)) fail(`Icons ${byName.get(name)} and ${icon.id} would both be "${name}".`);
  byName.set(name, icon.id);
  return { ...icon, name, category: categories.indexOf(categoryOf(icon)), ...extractSvg(icon.id) };
});

// ── Sources ──────────────────────────────────────────────────────────────

const quote = (value) => `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

const dataSource = `// ${GENERATED_MARKER} from @oicl/openbridge-webcomponents ${version} – do not edit.
// Regenerate with \`npm run create:icons\`${args.groups ? ` -- --groups ${JSON.stringify(args.groups)}` : ''}.

/** \`[id, name, category index, width, height, inner SVG markup]\` */
export type OpenBridgeIconData = readonly [
  id: string,
  name: string,
  category: number,
  width: number,
  height: number,
  markup: string,
];

export const OPENBRIDGE_ICON_CATEGORIES: readonly string[] = [
${categories.map((c) => `  ${quote(c)},`).join('\n')}
];

// prettier-ignore
export const OPENBRIDGE_ICONS: readonly OpenBridgeIconData[] = [
${entries.map((e) => `  [${quote(e.id)}, ${quote(e.name)}, ${e.category}, ${e.width}, ${e.height}, ${quote(e.markup)}],`).join('\n')}
];
`;

const sizeKb = Math.round(Buffer.byteLength(dataSource) / 1024);

if (args['dry-run']) {
  console.log(`Would write ${srcDir}/${DATA_FILE}: ${entries.length} icons, ${sizeKb} kB.`);
  for (const category of categories) {
    const count = entries.filter((e) => categories[e.category] === category).length;
    console.log(`  ${category} (${count})`);
  }
  if (!existsSync(inSrc(RUNTIME_FILE))) console.log(`Would create ${srcDir}/${RUNTIME_FILE}.`);
  process.exit(0);
}

// ── Write files ──────────────────────────────────────────────────────────

const existingData = readIfExists(inSrc(DATA_FILE));
if (existingData !== undefined && !existingData.includes(GENERATED_MARKER)) {
  fail(
    `${srcDir}/${DATA_FILE} exists and was not generated by this script – refusing to overwrite it.`,
  );
}

const writeFile = (file, source) => {
  mkdirSync(dirname(inRoot(file)), { recursive: true });
  writeFileSync(inRoot(file), source);
};

const written = [`${srcDir}/${DATA_FILE}`];
writeFile(`${srcDir}/${DATA_FILE}`, dataSource);
for (const [file, source] of Object.entries(runtimeFiles())) {
  if (existsSync(inSrc(file))) continue;
  writeFile(`${srcDir}/${file}`, source);
  written.push(`${srcDir}/${file}`);
  if (file === 'namespace.ts') {
    warn(
      `Created ${srcDir}/namespace.ts with a placeholder – set your reverse-domain namespace before publishing.`,
    );
  }
}

if (!args['no-register']) {
  const mainPath = inRoot(mainFile);
  const main = readIfExists(mainPath);
  if (main === undefined) {
    warn(`${mainFile} not found – register ${EXPORT_NAME} manually (icons: ${EXPORT_NAME}).`);
  } else if (!main.includes(EXPORT_NAME)) {
    const registered = registerIcons(main);
    if (registered === undefined) {
      warn(`Could not find where to add icons in ${mainFile} – register ${EXPORT_NAME} manually.`);
    } else {
      writeFileSync(mainPath, registered);
      written.push(mainFile);
    }
  }
}

/** Adds the import and `icons: openBridgeIcons` (or `...openBridgeIcons` to an existing array). */
function registerIcons(main) {
  let updated;
  const iconsKey = main.search(/\bicons\s*:\s*\[/);
  if (iconsKey >= 0) {
    const open = main.indexOf('[', iconsKey);
    updated = `${main.slice(0, open + 1)}...${EXPORT_NAME}, ${main.slice(open + 1)}`;
  } else if (/\bicons\s*:/.test(main)) {
    return undefined;
  } else {
    const call = main.search(/createLibraryExtension\(\s*\{/);
    const end = call < 0 ? -1 : main.lastIndexOf('});');
    if (end < 0) return undefined;
    const before = main.slice(0, end).trimEnd();
    const comma = before.endsWith(',') || before.endsWith('{') ? '' : ',';
    updated = `${before}${comma}\n\n  icons: ${EXPORT_NAME},\n${main.slice(end)}`;
  }
  let importPath = relative(dirname(inRoot(mainFile)), inSrc(RUNTIME_FILE)).replace(/\.tsx$/, '');
  if (!importPath.startsWith('.')) importPath = `./${importPath}`;
  const importLine = `import { ${EXPORT_NAME} } from '${importPath}';\n`;
  const lastImport = [...updated.matchAll(/^import [\s\S]*?;\n/gm)].pop();
  const at = lastImport ? lastImport.index + lastImport[0].length : 0;
  return updated.slice(0, at) + importLine + updated.slice(at);
}

const prettierBin = inRoot('node_modules/.bin/prettier');
if (existsSync(prettierBin)) {
  execFileSync(prettierBin, ['--write', ...written], { cwd: root, stdio: 'ignore' });
} else {
  warn('prettier is not installed locally – generated files are not formatted.');
}

console.log(
  `Added ${entries.length} OpenBridge icons (${categories.length} categories, ${sizeKb} kB):`,
);
for (const file of written) console.log(`  ${file}`);
for (const message of warnings) console.log(`\n\x1b[33mWarning:\x1b[0m ${message}`);

// ── Embedded runtime files ───────────────────────────────────────────────
// Written into a target project when missing. The synced one is a copy of
// this repo's file – refresh it with --sync-runtime after changing it.

function runtimeFiles() {
  return {
    ...syncedRuntimeFiles(),
    'namespace.ts': `import { createNamespace } from '@hmiproject/helio-sdk';

export const namespace = createNamespace({
  // Change this so it matches your company's domain name in
  // https://en.wikipedia.org/wiki/Reverse_domain_name_notation
  name: 'com.my-company.my-extension',
});
`,
  };
}

// @runtime-files-start
// prettier-ignore
function syncedRuntimeFiles() {
  return {
    "icons/openbridgeIcons.tsx": "import { createIcon, type CreateIconResult, type IconComponentProps } from '@hmiproject/helio-sdk';\nimport type { SVGProps } from 'react';\nimport { namespace } from '../namespace';\nimport {\n  OPENBRIDGE_ICON_CATEGORIES,\n  OPENBRIDGE_ICONS,\n  type OpenBridgeIconData,\n} from './openbridgeIcons.generated';\n\ntype OpenBridgeIconProps = IconComponentProps & SVGProps<SVGSVGElement>;\n\n/**\n * Turns one generated entry into a HELIO icon. The markup is OpenBridge's\n * `currentColor` variant, so the icon takes the color HELIO renders it with.\n * Like an imported SVG, it keeps its intrinsic size unless HELIO passes one.\n */\nexport function createOpenBridgeIcon(data: OpenBridgeIconData): CreateIconResult {\n  const [id, name, category, width, height, markup] = data;\n  const html = { __html: markup };\n\n  // `size` is HELIO's S/M/L hint; OpenBridge has one drawing for all sizes.\n  function Icon({ size: _size, children: _children, ...svgProps }: OpenBridgeIconProps) {\n    return (\n      <svg\n        xmlns=\"http://www.w3.org/2000/svg\"\n        width={width}\n        height={height}\n        viewBox={`0 0 ${width} ${height}`}\n        fill=\"currentColor\"\n        {...svgProps}\n        dangerouslySetInnerHTML={html}\n      />\n    );\n  }\n  Icon.displayName = `OpenBridgeIcon(${id})`;\n\n  return createIcon(namespace, {\n    name,\n    description: `obi-${id}`,\n    category: OPENBRIDGE_ICON_CATEGORIES[category],\n    Icon,\n  });\n}\n\nexport const openBridgeIcons: CreateIconResult[] = OPENBRIDGE_ICONS.map(createOpenBridgeIcon);\n",
  };
}
// @runtime-files-end

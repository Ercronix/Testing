/** Prefixes ids and their references (`url(#…)`, `href="#…"`) so icons cannot collide. */
function prefixIds(markup, prefix) {
  return markup
    .replace(/(\s)id=(["'])([^"']+)\2/g, `$1id="${prefix}$3"`)
    .replace(/url\((['"]?)#([^)'"]+)\1\)/g, `url(#${prefix}$2)`)
    .replace(/href=(["'])#([^"']+)\1/g, `href="#${prefix}$2"`);
}

const minify = (markup) => markup.replace(/>\s+</g, '><').replace(/\s+/g, ' ').trim();


function customIcons() {
  const from = args.from ?? 'icons';
  const dir = inRoot(from);
  if (!existsSync(dir) || !statSync(dir).isDirectory()) {
    fail(
      args.from === undefined
        ? `No icons/ folder in ${root}. Create one with .svg/.png files, or pass --from <dir> (or --openbridge).`
        : `--from: ${from} is not a folder.`,
    );
  }
  const category = args.category ?? extensionName() ?? basename(dir);
  const files = walk(dir);
  // Code next to the icons (e.g. --from src/icons) is not reported.
  const skipped = files.filter(
    (f) => !ICON_EXTENSIONS.includes(extname(f).toLowerCase()) && !/\.tsx?$/.test(f),
  );
  if (skipped.length) {
    warn(
      `Skipped ${skipped.length} file(s) that are not .svg/.png: ${skipped.map((f) => relative(dir, f)).join(', ')}`,
    );
  }
  const colored = [];
  const icons = files
    .filter((f) => ICON_EXTENSIONS.includes(extname(f).toLowerCase()))
    .map((file) => {
      const rel = relative(dir, file).split(sep).join('/');
      const folders = rel.split('/').slice(0, -1);
      const stem = basename(file, extname(file));
      const prefix = `${setName}-${slug(rel.replace(/\.[^.]+$/, ''))}-`;
      const isPng = extname(file).toLowerCase() === '.png';
      const icon = isPng ? readPng(file, prefix) : readSvg(file, prefix);
      if (icon.keptColors) colored.push(rel);
      return {
        name: fileName(stem),
        description: rel,
        category: [category, ...folders].join(' / '),
        ...icon,
      };
    });
  if (colored.length) {
    console.log(
      `Keeping own colors (multi-color SVG or untinted PNG – HELIO cannot recolor these): ${colored.join(', ')}`,
    );
  }
  return { source: relative(root, dir).split(sep).join('/') || '.', icons };
}

/** The `name` passed to createLibraryExtension in main.tsx. */
function extensionName() {
  const main = readIfExists(inRoot(mainFile)) ?? '';
  const call = main.slice(Math.max(0, main.search(/createLibraryExtension\(\s*\{/)));
  return call.match(/\bname\s*:\s*(['"`])((?:(?!\1).)+)\1/)?.[2];
}

function walk(dir) {
  return readdirSync(dir, { withFileTypes: true })
    .filter((entry) => !entry.name.startsWith('.'))
    .sort((a, b) => a.name.localeCompare(b.name))
    .flatMap((entry) =>
      entry.isDirectory() ? walk(resolve(dir, entry.name)) : [resolve(dir, entry.name)],
    );
}

const slug = (value) =>
  value
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');

/** `pump-running` / `pump_running` / `pump running` → "Pump Running"; other casing is kept. */
const fileName = (stem) =>
  stem
    .replace(/[-_\s]+/g, ' ')
    .trim()
    .replace(/(^|\s)(\S)/g, (_, space, letter) => space + letter.toUpperCase());

/** Scales `width × height` so the longer side is `--size`. */
function fitSize(width, height) {
  const scale = iconSize / Math.max(width, height);
  const round = (n) => Math.round(n * 1000) / 1000;
  return { scale, width: round(width * scale), height: round(height * scale) };
}

/** Presentation attributes of the `<svg>` root that its children inherit. */
const INHERITED_ATTRIBUTES = [
  'fill',
  'fill-opacity',
  'fill-rule',
  'clip-rule',
  'stroke',
  'stroke-width',
  'stroke-linecap',
  'stroke-linejoin',
  'stroke-miterlimit',
  'stroke-dasharray',
  'stroke-opacity',
  'opacity',
  'color',
  'style',
];

const NAMED_COLORS = { black: '#000000', white: '#ffffff' };

function normalizeColor(value) {
  const color = value.trim().toLowerCase();
  if (NAMED_COLORS[color]) return NAMED_COLORS[color];
  const short = color.match(/^#([0-9a-f])([0-9a-f])([0-9a-f])$/);
  return short ? `#${short[1]}${short[1]}${short[2]}${short[2]}${short[3]}${short[3]}` : color;
}

const isPaint = (value) =>
  !/^(none|currentcolor|transparent|inherit|url\(.*\))$/i.test(value.trim());

/** Color values in `fill`/`stroke`/`stop-color` attributes and style declarations. */
const COLOR_PATTERN =
  /((?:^|[\s;{"])(?:fill|stroke|stop-color|color)\s*[:=]\s*["']?)(url\([^)]*\)|#[0-9a-fA-F]{3,8}|rgba?\([^)]*\)|[a-zA-Z]+)/g;

/**
 * Reads an SVG file: moves the root's size, viewBox offset and inherited
 * attributes onto a `<g>` (the runtime renders its own `<svg>` root), switches
 * single-color icons to `currentColor` and prefixes ids and CSS classes.
 */
function readSvg(file, prefix) {
  const where = relative(root, file);
  const text = readFileSync(file, 'utf8')
    .replace(/<\?xml[\s\S]*?\?>/g, '')
    .replace(/<!DOCTYPE[\s\S]*?>/gi, '')
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/<(metadata|title|desc)\b[\s\S]*?<\/\1>/g, '')
    .replace(/<sodipodi:namedview\b[\s\S]*?(\/>|<\/sodipodi:namedview>)/g, '')
    .replace(/\s(?:inkscape|sodipodi):[\w-]+=(["'])[\s\S]*?\1/g, '');
  const svg = text.match(/<svg\b([^>]*?)(?:\/>|>([\s\S]*)<\/svg>)/);
  if (!svg) fail(`${where}: no <svg> element found.`);
  const attrs = Object.fromEntries(
    [...svg[1].matchAll(/([\w:-]+)\s*=\s*(?:"([^"]*)"|'([^']*)')/g)].map((m) => [
      m[1],
      m[2] ?? m[3],
    ]),
  );
  const length = (value) => (/^[\d.]+(px)?$/.test(value ?? '') ? parseFloat(value) : undefined);
  const viewBox = attrs.viewBox
    ?.trim()
    .split(/[\s,]+/)
    .map(Number);
  const [minX, minY, vbWidth, vbHeight] =
    viewBox?.length === 4 && viewBox.every(Number.isFinite)
      ? viewBox
      : [0, 0, length(attrs.width), length(attrs.height)];
  if (!(vbWidth > 0 && vbHeight > 0)) fail(`${where}: needs a viewBox or numeric width/height.`);

  let inner = svg[2] ?? '';
  if (/<(script|foreignObject)\b/i.test(inner))
    fail(`${where}: <script>/<foreignObject> is not supported.`);
  if (/<style\b/.test(inner)) {
    // Inline <style> applies to the whole page – scope class selectors to this icon.
    inner = inner
      .replace(/<style\b([^>]*)>([\s\S]*?)<\/style>/g, (_, styleAttrs, css) => {
        const selectors = css
          .replace(/\{[^}]*\}/g, ',')
          .split(',')
          .map((s) => s.trim());
        if (selectors.some((s) => /(^|[\s>+~])[a-zA-Z*]/.test(s.replace(/[.#][\w-]+/g, '')))) {
          warn(`${where}: <style> has element selectors – they style the whole HELIO page.`);
        }
        const scoped = css.replace(/\.(-?[_a-zA-Z][\w-]*)(?=[^{}]*\{)/g, `.${prefix}$1`);
        return `<style${styleAttrs}>${scoped}</style>`;
      })
      .replace(/\sclass=(["'])([^"']*)\1/g, (_, q, names) => {
        const scoped = names
          .split(/\s+/)
          .filter(Boolean)
          .map((n) => prefix + n)
          .join(' ');
        return ` class="${scoped}"`;
      });
  }
  inner = prefixIds(inner, prefix);

  // The runtime root has fill="currentColor"; an SVG without root fill is black by default.
  const groupAttrs = Object.fromEntries(
    INHERITED_ATTRIBUTES.filter((a) => attrs[a] !== undefined).map((a) => [a, attrs[a]]),
  );
  const rootSetsFill =
    groupAttrs.fill !== undefined || /(^|;)\s*fill\s*:/.test(groupAttrs.style ?? '');
  const colorSource = `${Object.entries(groupAttrs)
    .map(([k, v]) => ` ${k}="${v}"`)
    .join('')} ${inner}`;
  const colors = new Set(
    [...colorSource.matchAll(COLOR_PATTERN)]
      .map((m) => m[2])
      .filter(isPaint)
      .map(normalizeColor),
  );
  if (!rootSetsFill) colors.add('#000000');
  const monochrome = colors.size <= 1 && !args['keep-colors'];

  const recolor = (markup) =>
    markup.replace(COLOR_PATTERN, (match, head, value) =>
      isPaint(value) ? `${head}currentColor` : match,
    );
  if (monochrome) {
    inner = recolor(inner);
    for (const key of Object.keys(groupAttrs)) {
      groupAttrs[key] = recolor(` ${key}="${groupAttrs[key]}`).slice(key.length + 3);
    }
  } else if (!rootSetsFill) {
    groupAttrs.fill = 'black';
  }

  const { scale, width, height } = fitSize(vbWidth, vbHeight);
  const transform = [
    scale !== 1 && `scale(${Math.round(scale * 1e6) / 1e6})`,
    (minX || minY) && `translate(${-minX} ${-minY})`,
  ]
    .filter(Boolean)
    .join(' ');
  if (transform) groupAttrs.transform = transform;
  const open = Object.entries(groupAttrs)
    .map(([k, v]) => ` ${k}="${v.replace(/"/g, '&quot;')}"`)
    .join('');
  const markup = minify(open ? `<g${open}>${inner}</g>` : inner);
  return { width, height, markup, keptColors: !monochrome };
}

/** Embeds a PNG as data URL; with --tint its alpha channel masks a `currentColor` fill. */
function readPng(file, prefix) {
  const where = relative(root, file);
  const bytes = readFileSync(file);
  const signature = '89504e470d0a1a0a';
  if (
    bytes.subarray(0, 8).toString('hex') !== signature ||
    bytes.toString('ascii', 12, 16) !== 'IHDR'
  ) {
    fail(`${where}: not a valid PNG file.`);
  }
  if (bytes.length > 100 * 1024) {
    warn(`${where} is ${Math.round(bytes.length / 1024)} kB – it is embedded in the bundle as is.`);
  }
  const { width, height } = fitSize(bytes.readUInt32BE(16), bytes.readUInt32BE(20));
  const image = `<image href="data:image/png;base64,${bytes.toString('base64')}" width="${width}" height="${height}" preserveAspectRatio="none"/>`;
  const markup = args.tint
    ? `<mask id="${prefix}mask" mask-type="alpha" style="mask-type:alpha" maskUnits="userSpaceOnUse" x="0" y="0" width="${width}" height="${height}">${image}</mask><rect width="${width}" height="${height}" mask="url(#${prefix}mask)"/>`
    : image;
  return { width, height, markup, keptColors: !args.tint };
}


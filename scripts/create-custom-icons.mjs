/** Names in the other `*.generated.ts` icon sets of this project. */
function otherSetNames() {
  const iconsDir = inSrc('icons');
  if (!existsSync(iconsDir)) return [];
  return readdirSync(iconsDir)
    .filter((f) => f.endsWith('.generated.ts') && `icons/${f}` !== dataFile)
    .map((f) => {
      const text = readFileSync(resolve(iconsDir, f), 'utf8');
      const names = [...text.matchAll(/^\s*\['((?:[^'\\]|\\.)*)',/gm)].map((m) =>
        m[1].replace(/\\(.)/g, '$1'),
      );
      return [`${srcDir}/icons/${f}`, names];
    });
}


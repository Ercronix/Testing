/** Adds the import and the set to `icons` (creating the property or turning it into an array). */
function registerIcons(main) {
  let updated;
  const array = main.search(/\bicons\s*:\s*\[/);
  const single = main.match(/\bicons\s*:\s*([A-Za-z_$][\w$]*)\s*,/);
  if (array >= 0) {
    const open = main.indexOf('[', array);
    updated = `${main.slice(0, open + 1)}...${setName}, ${main.slice(open + 1)}`;
  } else if (single) {
    updated = main.replace(single[0], `icons: [...${single[1]}, ...${setName}],`);
  } else if (/\bicons\s*:/.test(main)) {
    return undefined;
  } else {
    const call = main.search(/createLibraryExtension\(\s*\{/);
    const end = call < 0 ? -1 : main.lastIndexOf('});');
    if (end < 0) return undefined;
    const before = main.slice(0, end).trimEnd();
    const comma = before.endsWith(',') || before.endsWith('{') ? '' : ',';
    updated = `${before}${comma}\n\n  icons: [...${setName}],\n${main.slice(end)}`;
  }
  const importLine = `import { ${setName} } from '${importPath(dataFile)}';\n`;
  const lastImport = [...updated.matchAll(/^import [\s\S]*?;\n/gm)].pop();
  const at = lastImport ? lastImport.index + lastImport[0].length : 0;
  return updated.slice(0, at) + importLine + updated.slice(at);
}

function importPath(file) {
  const path = relative(dirname(inRoot(mainFile)), inSrc(file))
    .split(sep)
    .join('/')
    .replace(/\.tsx?$/, '');
  return path.startsWith('.') ? path : `./${path}`;
}


import {
  createElement,
  createPropsSchema,
  dynamicProperties,
  props,
  traits,
  useAction,
  useDynamicProperty,
  useRenderMode,
  values,
} from '@hmiproject/helio-sdk';
import { Fragment } from 'react';
import { namespace } from '../namespace';
import {
  CommandMenu,
  commandMenuIcons,
  commandMenuModes,
  type CommandMenuIcon,
  type CommandMenuMode,
} from '../components/CommandMenu';
import { optionalString, toBoolean, writeValue } from '../utils/valueMapping';

/**
 * OpenBridge command menu (`<obc-command-button>` + `<obc-command-menu>`) as a
 * HELIO Control: shows whether this station is in command and lets the user
 * take or release it.
 *
 * Hand-written (not generated by `create-element.mjs`).
 */
export const commandMenuElement = createElement(namespace, {
  name: 'OpenBridge Command Menu',
  description:
    'Command button with a menu to take or release command of a station (OpenBridge design system).',
  category: 'OpenBridge',
  icon: { name: 'Toggles' },

  traits: [traits.Control],

  propsGroups: {
    data: { label: 'Values' },
    labels: { label: 'Labels', defaultClosed: true },
    display: { label: 'Display' },
    interaction: { label: 'Interaction', defaultClosed: true },
  },

  propsSchema: createPropsSchema().initial({
    inCommand: props.DynamicProperty({
      label: 'In command (written on toggle)',
      propGroup: 'data',
      valueType: 'Boolean',
      optional: false,
      defaultValue: dynamicProperties.DataVariable(),
    }),
    status: props.DynamicProperty({
      label: 'Status (e.g. Joystick)',
      propGroup: 'data',
      valueType: 'String',
      optional: true,
    }),
    description: props.DynamicProperty({
      label: 'Description (e.g. DP)',
      propGroup: 'data',
      valueType: 'String',
      optional: true,
    }),
    location: props.DynamicProperty({
      label: 'Location (e.g. Aft Bridge)',
      propGroup: 'data',
      valueType: 'String',
      optional: true,
    }),
    takeLabel: props.DynamicProperty({
      label: 'Take command action (default Take)',
      propGroup: 'labels',
      valueType: 'String',
      optional: true,
    }),
    releaseLabel: props.DynamicProperty({
      label: 'Release command action (default Release)',
      propGroup: 'labels',
      valueType: 'String',
      optional: true,
    }),
    inCommandLabel: props.DynamicProperty({
      label: 'In command state (default In CMD)',
      propGroup: 'labels',
      valueType: 'String',
      optional: true,
    }),
    noCommandLabel: props.DynamicProperty({
      label: 'No command state (default No CMD)',
      propGroup: 'labels',
      valueType: 'String',
      optional: true,
    }),
    mode: props.Enum({
      label: 'Mode (button opens the menu, menu is always visible)',
      propGroup: 'display',
      options: [...commandMenuModes],
      defaultValue: 'button',
      optional: true,
    }),
    icon: props.Enum({
      label: 'Icon (auto = command state)',
      propGroup: 'display',
      options: [...commandMenuIcons],
      defaultValue: 'auto',
      optional: true,
    }),
    onChange: props.Action({
      label: 'On change (after writing In command)',
      propGroup: 'interaction',
      optional: true,
    }),
  }),

  Component(p) {
    const renderMode = useRenderMode();
    const interactive = renderMode !== 'PreviewEdit';

    const inCommandDp = useDynamicProperty(p.inCommand, { valueType: values.Boolean() });
    const statusDp = useDynamicProperty(p.status, { valueType: values.String() });
    const descriptionDp = useDynamicProperty(p.description, { valueType: values.String() });
    const locationDp = useDynamicProperty(p.location, { valueType: values.String() });
    const takeLabelDp = useDynamicProperty(p.takeLabel, { valueType: values.String() });
    const releaseLabelDp = useDynamicProperty(p.releaseLabel, { valueType: values.String() });
    const inCommandLabelDp = useDynamicProperty(p.inCommandLabel, { valueType: values.String() });
    const noCommandLabelDp = useDynamicProperty(p.noCommandLabel, { valueType: values.String() });

    const onChange = useAction(p.onChange);

    // Dynamic properties need to be mounted to subscribe to value changes.
    const subscriptions = [
      inCommandDp,
      statusDp,
      descriptionDp,
      locationDp,
      takeLabelDp,
      releaseLabelDp,
      inCommandLabelDp,
      noCommandLabelDp,
    ];

    const inCommand =
      inCommandDp.canRead === false ? false : (toBoolean(inCommandDp.value) ?? false);

    return (
      <Fragment>
        {subscriptions.map((dp, index) => (
          <Fragment key={index}>{dp.render()}</Fragment>
        ))}
        {onChange.render()}

        <CommandMenu
          inCommand={inCommand}
          status={optionalString(p.status, statusDp)}
          description={optionalString(p.description, descriptionDp)}
          location={optionalString(p.location, locationDp)}
          takeLabel={optionalString(p.takeLabel, takeLabelDp)}
          releaseLabel={optionalString(p.releaseLabel, releaseLabelDp)}
          inCommandLabel={optionalString(p.inCommandLabel, inCommandLabelDp)}
          noCommandLabel={optionalString(p.noCommandLabel, noCommandLabelDp)}
          mode={p.mode as CommandMenuMode | undefined}
          icon={p.icon as CommandMenuIcon | undefined}
          disabled={!interactive}
          onChange={(next) => {
            writeValue(p.inCommand, inCommandDp, next);
            if (onChange.canCall === true) onChange.call();
          }}
        />
      </Fragment>
    );
  },
});
